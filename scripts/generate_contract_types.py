"""Generate TypeScript data types from this repository's bounded JSON Schema subset."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
C = ROOT / 'contracts'


def ts(schema):
    if '$ref' in schema:
        reference = schema['$ref']
        if reference == './report.schema.json':
            return 'Report'
        if reference.startswith('#/components/schemas/'):
            return reference.rsplit('/', 1)[1]
        raise ValueError(f'Unsupported reference: {reference}')
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(v, ensure_ascii=False) for v in schema['enum'])
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return ' | '.join(f'({ts(s)})' for s in schema[union])
    kind = schema.get('type')
    if kind in ('integer', 'number'):
        return 'number'
    if kind in ('string', 'boolean', 'null'):
        return kind
    if kind == 'array':
        return f'Array<{ts(schema["items"])}>'
    if kind == 'object':
        properties = schema.get('properties', {})
        if not properties:
            return 'Record<string, never>'
        required = set(schema.get('required', []))
        return '{\n' + '\n'.join(f'  {json.dumps(k)}{"" if k in required else "?"}: {ts(v)};'
                                 for k, v in properties.items()) + '\n}'
    raise ValueError(f'Unsupported schema: {schema}')


def generated():
    api = json.loads((C / 'openapi.json').read_text())
    lines = ['// Generated by scripts/generate_contract_types.py; do not edit.',
             '// Compile-time types only. Runtime schema, authorization and semantic checks remain required.',
             f'export const contractVersion = {json.dumps(api["info"]["version"])} as const;\n']
    for name, schema in api['components']['schemas'].items():
        lines.append(f'export type {name} = {ts(schema)};\n')
    lines.append('export type Report = ' + ts(json.loads((C / 'report.schema.json').read_text())) + ';\n')
    lines.append('export type AppEvent = ' + ts(json.loads((C / 'events.schema.json').read_text())) + ';\n')
    lines.append('export interface API {')
    routes = {}
    for path, methods in api['paths'].items():
        for method, operation in methods.items():
            name = operation['operationId']
            body = operation.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema')
            params = {p['name']: p['schema'] for p in operation['parameters'] if p.get('in') == 'path'}
            path_type = ts({'type':'object','properties':params,'required':list(params)})
            responses = []
            for status, response in operation['responses'].items():
                content = response.get('content', {})
                schema = content.get('application/json', {}).get('schema')
                response_type = ts(schema) if schema else 'string'
                responses.append(f'{{ status: {status}; body: {response_type} }}')
            lines.append(f'  {name}: {{ method: {json.dumps(method.upper())}; path: {json.dumps(path)}; '
                         f'pathParams: {path_type}; request: {ts(body) if body else "never"}; '
                         f'response: {" | ".join(responses)} }};')
            routes[name] = {'method':method.upper(),'path':path,'roles':operation['x-roles']}
    lines += ['}', 'export type OperationId = keyof API;',
              'export type RequestOf<K extends OperationId> = API[K]["request"];',
              'export type ResponseOf<K extends OperationId> = API[K]["response"];', '']
    return {'api.ts':'\n'.join(lines), 'routes.json':json.dumps(routes,ensure_ascii=False,indent=2)+'\n'}


if __name__ == '__main__':
    args = argparse.ArgumentParser()
    args.add_argument('--check', action='store_true')
    check = args.parse_args().check
    output = C / 'generated'
    if not check:
        output.mkdir(exist_ok=True)
    for filename, content in generated().items():
        path = output / filename
        if check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Stale generated artifact: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    print('Generated TypeScript/routes are current.' if check else 'Generated TypeScript/types and operation routes.')
